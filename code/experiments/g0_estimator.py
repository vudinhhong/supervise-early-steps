r"""G0 -- do the estimators of C2 recover a known C2?  (CPU only)

Runs on the exactly solvable world of ``scd.synthetic``, where the coefficient is
computable by summation.  Three things are checked, and they are different things
that a single "does it work" test would conflate:

  G0.0  the world is a fit instrument at all: the dependent variable has range,
        and the fidelity--capability dissociation occurs in it somewhere.
  G0.2  the data-processing inequality holds numerically: an estimator that
        coarsens returns a lower bound.
  G0.3  sampling accuracy, against the *coarsened* exact value -- so an estimator
        is not blamed for a property of its feature map.
  G0.4  rank agreement with the *full* exact value, which is what the method needs.

Configurations are generated by a documented random procedure from a committed
seed (validity condition V1.2).  Nothing here is hand-picked.
"""

from __future__ import annotations

import argparse
import itertools
import json

import numpy as np

from scd import coverage, runio, stats, synthetic as SY


def build_configs(n_worlds: int, ks, H: int, seed0: int):
    """(world, capacity, mu) triples -- the pre-registered grid."""
    out = []
    for ws in range(n_worlds):
        w = SY.make_world(seed0 + ws, H=H)
        d = SY.occupancy(w, w.pi_t)
        JT = SY.value(w, w.pi_t)
        fam = SY.mu_family(w, seed=seed0 + 1000 + ws)
        for k in ks:
            groups = SY.capacity_groups(w.ns, k, np.random.default_rng(seed0 + 7 * ws + k))
            for name, mu in fam.items():
                out.append(dict(world=ws, k=k, mu_name=name, w=w, d=d, JT=JT,
                                mu=mu, groups=groups))
    return out


def exact_row(c) -> dict:
    w, d, mu = c["w"], c["d"], c["mu"]
    pi_s = SY.student_from_mu(w, mu, c["groups"])
    kl = SY.kl_per_state(w, pi_s)
    mu_raw = mu / mu.sum()
    mu_sm = SY.smoothed(mu, w.ns)
    gap = c["JT"] - SY.value(w, pi_s)
    # The theorem is checked under ONE measure; the practitioner's pair -- the
    # numbers a distillation paper would actually report -- is recorded beside it.
    c2_sm = SY.c2_exact(d, mu_sm)
    e_sm = float((mu_sm * kl).sum())
    c2_raw = SY.c2_exact(d, mu_raw)
    e_raw = float((mu_raw * kl).sum())
    return dict(world=c["world"], k=c["k"], mu_name=c["mu_name"],
                family="hole" if c["mu_name"].startswith(("hole", "head")) else "mix",
                c2_exact=c2_sm, e_kl_mu=e_sm,
                c2_raw=c2_raw, e_kl_mu_raw=e_raw,
                e_kl_d=float((d * kl).sum()),
                gap=gap, bound=SY.bound(w, c2_sm, e_sm),
                mu_smoothed=mu_sm)


def estimate_row(c, row, n: int, rep: int, sigma_cells: int) -> dict:
    w, d = c["w"], c["d"]
    rng = np.random.default_rng(10_000 * rep + 13 * c["k"] + c["world"])
    mu_sm = row["mu_smoothed"]
    s_d = SY.sample_states(d, n, rng)
    s_mu = SY.sample_states(mu_sm, n, rng)

    sig = SY.sigma_codes(w.ns, sigma_cells)
    A = coverage.c2_counting(sig[s_d], sig[s_mu], sigma_cells)
    exact_sigma = SY.c2_exact(SY.coarsen(d, sig, sigma_cells),
                              SY.coarsen(mu_sm, sig, sigma_cells))

    F_d = SY.features(s_d, w.ns)
    F_mu = SY.features(s_mu, w.ns)
    B = coverage.c2_density_ratio(F_d, F_mu, seed=rep)
    C = coverage.c2_knn(F_d, F_mu, seed=rep)
    return dict(n=n, rep=rep, c2_A=A["c2"], c2_A_unclipped=A["c2_unclipped"],
                c2_B=B["c2"], auc_B=B["auc"], c2_C=C["c2"],
                exact_sigma=exact_sigma,
                exact_feature=SY.c2_exact(d, mu_sm))   # features = state identity


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--worlds", type=int, default=10)
    ap.add_argument("--ks", type=str, default="4 8 16 32 64")
    ap.add_argument("--horizon", type=int, default=40)
    ap.add_argument("--seed0", type=int, default=20260401)
    ap.add_argument("--ns", type=str, default="1000 10000 100000")
    ap.add_argument("--reps", type=int, default=3)
    ap.add_argument("--sigma-cells", type=int, default=16)
    ap.add_argument("--tag", type=str, default="g0_estimator")
    a = ap.parse_args()

    ks = [int(x) for x in a.ks.split()]
    ns_list = [int(x) for x in a.ns.split()]
    cfgs = build_configs(a.worlds, ks, a.horizon, a.seed0)
    print(f"[g0] {len(cfgs)} configurations "
          f"({a.worlds} worlds x {len(ks)} capacities x {len(cfgs)//(a.worlds*len(ks))} measures)")

    exact = [exact_row(c) for c in cfgs]
    est = []
    for i, (c, row) in enumerate(zip(cfgs, exact)):
        for n, rep in itertools.product(ns_list, range(a.reps)):
            e = estimate_row(c, row, n, rep, a.sigma_cells)
            e.update(world=c["world"], k=c["k"], mu_name=c["mu_name"],
                     family=row["family"])
            est.append(e)
        if (i + 1) % 20 == 0:
            print(f"    [g0] {i+1}/{len(cfgs)} configurations estimated", flush=True)

    for r in exact:
        r.pop("mu_smoothed", None)

    gap = np.array([r["gap"] for r in exact])
    ekl = np.array([r["e_kl_mu"] for r in exact])
    c2 = np.array([r["c2_exact"] for r in exact])
    bnd = np.array([r["bound"] for r in exact])

    # --- G0.0 world validity
    dissoc = [(r["mu_name"], r["k"], r["e_kl_mu"], r["gap"])
              for r in exact if r["e_kl_mu"] <= 1e-2 and r["gap"] >= 0.10]
    world = {"gap_min": float(gap.min()), "gap_max": float(gap.max()),
             "gap_sd": float(gap.std(ddof=1)),
             "ekl_min": float(ekl.min()), "ekl_max": float(ekl.max()),
             "c2_min": float(c2.min()), "c2_max": float(c2.max()),
             "rho_c2_ekl": stats.spearman(c2, ekl)["rho"],
             "n_dissociating": len(dissoc), "dissociating_examples": dissoc[:8],
             "theorem1_violations": int((gap > bnd + 1e-12).sum()),
             "n_configs": len(exact)}

    # --- G0.2/G0.3/G0.4 estimator quality, at the largest sample size
    big = [e for e in est if e["n"] == max(ns_list)]
    acc, low = {}, {}
    for key, ref in (("c2_A", "exact_sigma"), ("c2_B", "exact_feature"),
                     ("c2_C", "exact_feature")):
        rel = np.array([abs(e[key] / e[ref] - 1.0) if e[ref] > 0 else np.nan
                        for e in big], float)
        acc[key] = {"median_rel_err": float(np.nanmedian(rel)),
                    "frac_within_20pct": float(np.nanmean(rel <= 0.20)),
                    "n": int(np.isfinite(rel).sum())}
    # clipping makes a *lower* bound the expected relation, so test it as such
    lowbound = np.array([e["c2_A"] <= e["exact_sigma"] * 1.05 + 1e-9 for e in big])
    low["A_le_exact_sigma"] = float(lowbound.mean())
    low["sigma_le_full"] = float(np.mean([e["exact_sigma"] <= e["exact_feature"] * 1.05 + 1e-9
                                          for e in big]))

    rank = {}
    for key in ("c2_A", "c2_B", "c2_C"):
        x = np.array([e[key] for e in big], float)
        y = np.array([e["exact_feature"] for e in big], float)
        rank[key] = stats.spearman(x, y)
    pair = {}
    for a1, b1 in (("c2_A", "c2_B"), ("c2_A", "c2_C"), ("c2_B", "c2_C")):
        pair[f"{a1}~{b1}"] = stats.spearman([e[a1] for e in big], [e[b1] for e in big])

    cv = {}
    for key in ("c2_A", "c2_B", "c2_C"):
        vals = {}
        for e in est:
            if e["n"] != 10_000:
                continue
            vals.setdefault((e["world"], e["k"], e["mu_name"]), []).append(e[key])
        cvs = [float(np.std(v, ddof=1) / abs(np.mean(v))) for v in vals.values()
               if len(v) > 1 and abs(np.mean(v)) > 1e-12]
        cv[key] = {"median_cv": float(np.median(cvs)) if cvs else float("nan"),
                   "frac_cv_le_0.2": float(np.mean(np.array(cvs) <= 0.2)) if cvs else float("nan")}

    conv = {}
    for key in ("c2_A", "c2_B", "c2_C"):
        per_n = {}
        for e in est:
            ref = e["exact_sigma"] if key == "c2_A" else e["exact_feature"]
            if ref > 0:
                per_n.setdefault(e["n"], []).append(abs(e[key] / ref - 1.0))
        conv[key] = {str(n): float(np.median(v)) for n, v in sorted(per_n.items())}

    runio.save(a.tag, {"args": vars(a), "world_validity": world,
                       "accuracy": acc, "lower_bound": low, "rank": rank,
                       "pairwise": pair, "stability_cv": cv, "convergence": conv,
                       "exact": exact, "estimates": est})

    print("\n--- G0 summary -------------------------------------------------")
    print(f"  world: gap {world['gap_min']:.3f}..{world['gap_max']:.3f} "
          f"(sd {world['gap_sd']:.3f}), C2 {world['c2_min']:.1f}..{world['c2_max']:.0f}")
    print(f"  Theorem 1 violations: {world['theorem1_violations']}/{world['n_configs']}")
    print(f"  dissociating configs (E_mu[KL]<=0.01 and gap>=0.10): {world['n_dissociating']}")
    for key in ("c2_A", "c2_B", "c2_C"):
        print(f"  {key}: rank vs exact rho={rank[key]['rho']:+.3f}  "
              f"within20%={acc[key]['frac_within_20pct']:.2f}  "
              f"median CV={cv[key]['median_cv']:.3f}")
    for k, v in pair.items():
        print(f"  pairwise {k}: rho={v['rho']:+.3f}")


if __name__ == "__main__":
    main()
